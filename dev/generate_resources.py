"""Generate the sorted C++ catalogue from one editable UTF-8 resource file."""
import json
import re
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mods/local/seamless-launchpad'

def literal(text):
    return 'L' + json.dumps(text, ensure_ascii=False)

def main():
    version = json.loads((ROOT / 'ryjs-project.json').read_text(encoding='utf-8'))['version']
    (ROOT / 'dev/mod_build.h').write_text('#pragma once\n#define WH_MOD_ID L"ryjs-launchpad"\n#define WH_MOD_VERSION L"' + version + '"\n',encoding='utf-8')
    preview_header = ROOT / 'dev/preview/preview_api.h'
    preview_header.write_text(re.sub(r'#define WH_MOD_VERSION L"[^"]*"', '#define WH_MOD_VERSION L"' + version + '-preview"', preview_header.read_text(encoding='utf-8')),encoding='utf-8')
    strings = json.loads((ROOT / 'dev/strings.zh-CN.json').read_text(encoding='utf-8'))
    rows = '\n'.join('    {' + literal(k) + ', ' + literal(v) + '},' for k, v in sorted(strings.items()))
    (MOD / 'launchpad_strings.inc').write_text('// Generated by dev/generate_resources.py. Edit dev/strings.zh-CN.json.\n' + rows + '\n', encoding='utf-8')
    source = MOD / 'seamless-launchpad.wh.cpp'
    text = source.read_text(encoding='utf-8')
    text = re.sub(r'^// @version\s+.*$', '// @version         ' + version, text, flags=re.M)
    extension = json.loads((ROOT / 'dev/settings-extension.json').read_text(encoding='utf-8'))
    fieldRows = []
    for field in extension:
        default = ('1' if field['default'] else '0') if isinstance(field['default'], bool) else str(field['default'])
        options = '{' + ', '.join('{' + literal(k) + ', ' + literal(v) + '}' for k,v in field.get('options', {}).items()) + '}'
        values = ['K::'+field['type'], literal(field['key']), literal(field['label']), literal(field['description']), literal(default), options,
                  str(field.get('min',0)), str(field.get('max',100)), str(field['page']), literal(field['group'])]
        fieldRows.append('{' + ', '.join(values) + '},')
    fieldBlock = '// Custom settings begin\n' + '\n'.join(fieldRows) + '\n// Custom settings end'
    if '// Custom settings begin' in text:
        text = re.sub(r'// Custom settings begin[\s\S]*?// Custom settings end', lambda _: fieldBlock, text)
    else:
        text = text.replace('    std::vector<SetField> fields = {', '    std::vector<SetField> fields = {\n' + fieldBlock)
    marker = '// ==WindhawkModSettings==\n/*\n'
    begin = text.index(marker) + len(marker)
    end = text.index('\n*/', begin)
    schema = yaml.safe_load(text[begin:end])
    for item in schema:
        if 'gridLayout' in item: item['gridLayout']='groups'
        if 'gridLayout' in item and not any('groups' in o for o in item.get('$options', [])):
            item['$options'].append({'groups':'Expanded groups'})
    for field in extension:
        item = next((x for x in schema if field['key'] in x), None)
        if item is None:
            item = {}; schema.append(item)
        item.update({field['key']:field['default'], '$name':field['label'], '$description':field['description']})
        if 'options' in field: item['$options'] = [{k:v} for k,v in field['options'].items()]
    missing = set()
    def localize(items):
        for field in items:
            for key in list(field):
                if key in ('$name', '$description'):
                    english = field[key]
                    if english not in strings: missing.add(english)
                    else: field[key + ':zh-CN'] = strings[english]
                elif key == '$options':
                    translated = []
                    for option in field[key]:
                        translated.append({k: strings.get(v, v) for k,v in option.items()})
                        missing.update(v for v in option.values() if v not in strings)
                    field['$options:zh-CN'] = translated
                elif not key.startswith('$') and isinstance(field[key], list):
                    localize(field[key])
    localize(schema)
    if missing: raise ValueError('Untranslated settings: ' + repr(sorted(missing)))
    defaults = {}
    def collect_defaults(items, prefix=''):
        for item in items:
            for key, value in item.items():
                if key.startswith('$'): continue
                name = prefix + key
                if isinstance(value, list): collect_defaults(value, name + '.')
                else: defaults[name] = ('1' if value else '0') if isinstance(value, bool) else str(value)
    collect_defaults(schema)
    (ROOT / 'dev/settings-defaults.json').write_text(json.dumps(defaults, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    localized = yaml.safe_dump(schema, allow_unicode=True, sort_keys=False, width=110)
    source.write_text(text[:begin] + localized.rstrip() + text[end:], encoding='utf-8')
    # A single-file source for the Windhawk editor: no local include deployment needed.
    packed = source.read_text(encoding='utf-8')
    header = (MOD / 'launchpad_i18n.h').read_text(encoding='utf-8').replace('#pragma once\n', '')
    header = header.replace('#include "launchpad_strings.inc"', (MOD / 'launchpad_strings.inc').read_text(encoding='utf-8'))
    packed = packed.replace('#include "launchpad_i18n.h"', header)
    packed = packed.replace('#include "launchpad_presenter.h"', (MOD / 'launchpad_presenter.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_metrics.h"', (MOD / 'launchpad_metrics.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_settings_store.h"', (MOD / 'launchpad_settings_store.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_start_button.h"', (MOD / 'launchpad_start_button.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include \"ryjs_data.h\"', (MOD / 'ryjs_data.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    for fragment in ['launchpad_groups_layout.inc', 'launchpad_groups_actions.inc', 'launchpad_svg.inc', 'launchpad_entries.inc', 'launchpad_group_positions.inc', 'launchpad_group_edit.inc', 'launchpad_web_icons.inc', 'launchpad_entry_editor.inc']:
        if (MOD / fragment).exists(): packed = packed.replace('#include "' + fragment + '"', (MOD / fragment).read_text(encoding='utf-8'))
    output = ROOT / 'build'
    output.mkdir(exist_ok=True)
    (output / 'ryjs-launchpad.wh.cpp').write_text(packed, encoding='utf-8')
    (ROOT / 'ryjs-launchpad.wh.cpp').write_text(packed, encoding='utf-8')
    print(f'Generated {len(strings)} Chinese resources')

if __name__ == '__main__':
    main()
