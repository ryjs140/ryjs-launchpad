"""Generate the sorted C++ catalogue from one editable UTF-8 resource file."""
import json
import re
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mods/local/ryjs-launchpad'

PREVIEW_ONLY = re.compile(r'^[ \t]*#if(n?)def[ \t]+SEAMLESS_PREVIEW[ \t]*$')
OTHER_DIRECTIVE = re.compile(r'^[ \t]*#(?:if|ifdef|ifndef|elif|else|endif)\b')


def literal(text):
    return 'L' + json.dumps(text, ensure_ascii=False)


def _matching_directive(lines, start):
    """The index of the #else or #endif which closes the block at start."""
    depth = 0
    for index in range(start, len(lines)):
        if not OTHER_DIRECTIVE.match(lines[index]):
            continue
        keyword = lines[index].strip().split()[0]
        if keyword in ('#if', '#ifdef', '#ifndef'):
            depth += 1
        elif keyword == '#endif':
            depth -= 1
            if depth == 0:
                return index, 'endif'
        elif keyword == '#else' and depth == 1:
            return index, 'else'
    raise ValueError('Unbalanced preview conditional: ' + lines[start].strip())


def _matching_endif(lines, start):
    """The index of the #endif which closes the block at start."""
    depth = 0
    for index in range(start, len(lines)):
        if not OTHER_DIRECTIVE.match(lines[index]):
            continue
        keyword = lines[index].strip().split()[0]
        if keyword in ('#if', '#ifdef', '#ifndef'):
            depth += 1
        elif keyword == '#endif':
            depth -= 1
            if depth == 0:
                return index
    raise ValueError('Unbalanced conditional: ' + lines[start].strip())


def strip_preview(text):
    """Resolve the preview branches the way a build without the macro does.

    The submitted file is read by the library's symbol extractor, which only
    resolves architecture macros: a symbol block under `#ifndef
    SEAMLESS_PREVIEW` is an unresolved condition and fails that check. The
    preview build keeps compiling the full source, so nothing is lost.
    """
    lines = text.splitlines(keepends=True)
    out = []
    index = 0
    while index < len(lines):
        line = lines[index]
        match = PREVIEW_ONLY.match(line.rstrip('\r\n'))
        if not match:
            out.append(line)
            index += 1
            continue
        boundary, kind = _matching_directive(lines, index)
        if match.group(1) == 'n':
            # #ifndef SEAMLESS_PREVIEW: the body is the real code.
            body = ''.join(lines[index + 1:boundary])
            out.extend(strip_preview(body).splitlines(keepends=True))
            # A block with #else keeps its alternative out of the build.
            end = _matching_endif(lines, index)
            index = end + 1
            continue
        if kind == 'else':
            end = _matching_endif(lines, index)
            body = ''.join(lines[boundary + 1:end])
            out.extend(strip_preview(body).splitlines(keepends=True))
            index = end + 1
        else:
            index = boundary + 1
    return ''.join(out)


def main():
    worker = (ROOT / 'dev/full_backup_worker.ps1').read_text(encoding='utf-8-sig')
    version = json.loads((ROOT / 'ryjs-project.json').read_text(encoding='utf-8'))['version']
    (ROOT / 'dev/mod_build.h').write_text('#pragma once\n#define WH_MOD_ID L"ryjs-launchpad"\n#define WH_MOD_VERSION L"' + version + '"\n',encoding='utf-8')
    preview_header = ROOT / 'dev/preview/preview_api.h'
    preview_header.write_text(re.sub(r'#define WH_MOD_VERSION L"[^"]*"', '#define WH_MOD_VERSION L"' + version + '-preview"', preview_header.read_text(encoding='utf-8')),encoding='utf-8')
    strings = json.loads((ROOT / 'dev/strings.zh-CN.json').read_text(encoding='utf-8'))
    rows = '\n'.join('    {' + literal(k) + ', ' + literal(v) + '},' for k, v in sorted(strings.items()))
    (MOD / 'launchpad_strings.inc').write_text('// Generated by dev/generate_resources.py. Edit dev/strings.zh-CN.json.\n' + rows + '\n', encoding='utf-8')
    source = MOD / 'ryjs-launchpad.wh.cpp'
    text = source.read_text(encoding='utf-8')
    text = re.sub(r'^// @version\s+.*$', '// @version         ' + version, text, flags=re.M)
    extension = json.loads((ROOT / 'dev/settings-extension.json').read_text(encoding='utf-8'))
    fieldRows = []
    for field in extension:
        default = ('1' if field['default'] else '0') if isinstance(field['default'], bool) else str(field['default'])
        options = '{' + ', '.join('{' + literal(k) + ', ' + literal(v) + '}' for k,v in field.get('options', {}).items()) + '}'
        values = ['K::'+field['type'], literal(field['key']), literal(field['label']), literal(field.get('description','')), literal(default), options,
                  str(field.get('min',0)), str(field.get('max',100)), str(field['page']), literal(field['group'])]
        fieldRows.append('{' + ', '.join(values) + '},')
    fieldBlock = '// Custom settings begin\n' + '\n'.join(fieldRows) + '\n// Custom settings end'
    if '// Custom settings begin' in text:
        text = re.sub(r'// Custom settings begin[\s\S]*?// Custom settings end', lambda _: fieldBlock, text)
    else:
        text = text.replace('    std::vector<SetField> fields = {', '    std::vector<SetField> fields = {\n' + fieldBlock)
    marker = '// ==WindhawkModSettings==\n/*\n'
    begin = text.index(marker) + len(marker)
    end = text.index('\n*/', begin)
    schema = yaml.safe_load(text[begin:end])
    schema = [item for item in schema if not any(key in item for key in ('labelPlateOpacity','labelRadius','labelShadow','textColor'))]
    for item in schema:
        if 'gridLayout' in item: item['gridLayout']='groups'
        if 'gridLayout' in item and not any('groups' in o for o in item.get('$options', [])):
            item['$options'].append({'groups':'Expanded groups'})
    for field in extension:
        item = next((x for x in schema if field['key'] in x), None)
        if item is None:
            item = {}; schema.append(item)
        item.update({field['key']:field['default'], '$name':field['label']})
        if field.get('description'): item['$description'] = field['description']
        if 'options' in field: item['$options'] = [{k:v} for k,v in field['options'].items()]
    missing = set()
    def localize(items):
        seen = set()
        for field in items:
            for key in list(field):
                if key in ('$name', '$description'):
                    english = field[key]
                    if english not in strings: missing.add(english)
                    else: field[key + ':zh-CN'] = strings[english]
                elif key == '$options':
                    translated = []
                    for option in field[key]:
                        translated.append({k: strings.get(v, v) for k,v in option.items()})
                        missing.update(v for v in option.values() if v not in strings)
                    field['$options:zh-CN'] = translated
                elif not key.startswith('$'):
                    if '.' in key:
                        raise ValueError(f'Windhawk settings require nested YAML for {key!r}')
                    if key in seen:
                        raise ValueError(f'Duplicate Windhawk settings ID {key!r}')
                    seen.add(key)
                    if isinstance(field[key], list):
                        localize(field[key])
    localize(schema)
    if missing: raise ValueError('Untranslated settings: ' + repr(sorted(missing)))
    defaults = {}
    def collect_defaults(items, prefix=''):
        for item in items:
            for key, value in item.items():
                if key.startswith('$'): continue
                name = prefix + key
                if isinstance(value, list): collect_defaults(value, name + '.')
                else: defaults[name] = ('1' if value else '0') if isinstance(value, bool) else str(value)
    collect_defaults(schema)
    default_rows = ''.join(
        f'        {{{literal(key)}, {literal(value)}}},\n'
        for key, value in sorted(defaults.items()))
    (MOD / 'launchpad_backup_script.inc').write_text(
        '// Generated from dev/full_backup_worker.ps1 and the settings schema.\n'
        'constexpr wchar_t kFullBackupScript[] = LR"RYJS_BACKUP(' + worker + ')RYJS_BACKUP";\n'
        'constexpr wchar_t kFullBackupDefaults[] = LR"RYJS_DEFAULTS(' +
        json.dumps(defaults, ensure_ascii=False) + ')RYJS_DEFAULTS";\n'
        'std::wstring_view DeclaredSettingDefault(std::wstring_view key) {\n'
        '    static constexpr std::pair<std::wstring_view, std::wstring_view> defaults[] = {\n'
        + default_rows +
        '    };\n'
        '    const auto match = std::lower_bound(std::begin(defaults), std::end(defaults), key,\n'
        '        [](const auto& item, std::wstring_view name) { return item.first < name; });\n'
        '    return match != std::end(defaults) && match->first == key ? match->second : std::wstring_view{};\n'
        '}\n', encoding='utf-8')
    (ROOT / 'dev/settings-defaults.json').write_text(json.dumps(defaults, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    localized = yaml.safe_dump(schema, allow_unicode=True, sort_keys=False, width=110)
    source.write_text(text[:begin] + localized.rstrip() + text[end:], encoding='utf-8')
    # A single-file source for the Windhawk editor: no local include deployment needed.
    packed = source.read_text(encoding='utf-8')
    # The preview header exists only for dev/preview, which defines
    # SEAMLESS_PREVIEW before including this file. Windhawk never defines it,
    # and the submitted file must not name a local header at all.
    packed = packed.replace('#include "preview_api.h"',
                            '// preview_api.h is used by dev/preview only, never by the mod.')
    header = (MOD / 'launchpad_i18n.h').read_text(encoding='utf-8').replace('#pragma once\n', '')
    header = header.replace('#include "launchpad_strings.inc"', (MOD / 'launchpad_strings.inc').read_text(encoding='utf-8'))
    packed = packed.replace('#include "launchpad_i18n.h"', header)
    packed = packed.replace('#include "launchpad_presenter.h"', (MOD / 'launchpad_presenter.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_metrics.h"', (MOD / 'launchpad_metrics.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_fly_in.h"', (MOD / 'launchpad_fly_in.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_settings_store.h"', (MOD / 'launchpad_settings_store.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_start_button.h"', (MOD / 'launchpad_start_button.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include \"ryjs_data.h\"', (MOD / 'ryjs_data.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    packed = packed.replace('#include "launchpad_lifecycle.h"', (MOD / 'launchpad_lifecycle.h').read_text(encoding='utf-8').replace('#pragma once\n', ''))
    for fragment in ['launchpad_material.h', 'launchpad_start_xaml.h', 'launchpad_contrast.inc', 'launchpad_groups_layout.inc', 'launchpad_groups_actions.inc', 'launchpad_svg.inc', 'launchpad_entries.inc', 'launchpad_display_names.inc', 'launchpad_group_positions.inc', 'launchpad_group_edit.inc', 'launchpad_app_icon.inc', 'launchpad_web_icons.inc', 'launchpad_entry_editor.inc', 'launchpad_full_backup.inc', 'launchpad_backup_script.inc']:
        if (MOD / fragment).exists():
            contents = (MOD / fragment).read_text(encoding='utf-8').removeprefix('#pragma once\n')
            packed = packed.replace('#include "' + fragment + '"', contents)
    includes = set(re.findall(r'^\s*#\s*include\s*"([^"]+)"', packed, flags=re.M))
    remaining = includes - {'preview_api.h'}  # Only used by SEAMLESS_PREVIEW.
    if remaining:
        raise ValueError('Standalone Windhawk source still includes: ' + ', '.join(sorted(remaining)))
    # Resolve the preview branches the way a Windhawk build does, so the
    # submitted file carries no condition the library's symbol extractor
    # cannot evaluate. dev/preview still compiles the full source.
    packed = strip_preview(packed)
    if 'SEAMLESS_PREVIEW' in packed:
        raise ValueError('Standalone source still mentions SEAMLESS_PREVIEW')
    if re.search(r'^\s*#\s*pragma\s+once\b', packed, flags=re.M):
        raise ValueError('Standalone source still contains a header-only #pragma once')
    output = ROOT / 'build'
    output.mkdir(exist_ok=True)
    # Write LF on every platform: this file is submitted verbatim, and Git
    # normalises text to LF on commit anyway. Without this, the working copy
    # (CRLF) and the committed blob (LF) hash differently, and the SHA256 in
    # release/BUILD_RECORD.md would not match the file on GitHub.
    (output / 'ryjs-launchpad.wh.cpp').write_text(packed, encoding='utf-8', newline='\n')
    root_source = ROOT / 'ryjs-launchpad.wh.cpp'
    temporary_source = root_source.with_suffix('.cpp.tmp')
    temporary_source.write_text(packed, encoding='utf-8', newline='\n')
    temporary_source.replace(root_source)
    print(f'Generated {len(strings)} Chinese resources')

if __name__ == '__main__':
    main()
